    function setLang(lang) {
        currentLang = lang === 'en' ? 'en' : 'ru';
        document.documentElement.lang = currentLang;
        const toggleBtn = document.getElementById('lang-toggle');
        if (toggleBtn) toggleBtn.textContent = currentLang.toUpperCase();

        document.querySelectorAll('[data-i18n]').forEach((el) => {
            const key = el.dataset.i18n;
            if (DICT[currentLang][key] !== undefined) {
                el.textContent = DICT[currentLang][key];
            }
        });
        document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
            const key = el.dataset.i18nPlaceholder;
            if (DICT[currentLang][key] !== undefined) {
                el.setAttribute('placeholder', DICT[currentLang][key]);
            }
        });
        document.querySelectorAll('[data-i18n-title]').forEach((el) => {
            const key = el.dataset.i18nTitle;
            if (DICT[currentLang][key] !== undefined) {
                el.setAttribute('title', DICT[currentLang][key]);
            }
        });
        document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
            const key = el.dataset.i18nAria;
            if (DICT[currentLang][key] !== undefined) {
                el.setAttribute('aria-label', DICT[currentLang][key]);
            }
        });

        try { localStorage.setItem('neonhub-lang', currentLang); } catch (e) {}

        const meta = SEO_ROUTES[window.location.pathname] || SEO_ROUTES['/'];
        if (meta && meta.title && meta.title[currentLang]) {
            document.title = meta.title[currentLang];
        }
        const descEl = document.querySelector('meta[name="description"]');
        if (descEl) {
            descEl.setAttribute('content', currentLang === 'en'
                ? 'Neon Hub — local browser tools with no server uploads: de-AI text cleaner, photo censor & EXIF remover, background remover, PDF tools, batch image compressor, Whisper transcription, and QR generator.'
                : 'Neon Hub — браузерные инструменты без загрузки на сервер: очистка текста от ИИ-следов, цензор фото и удаление EXIF, удаление фона, работа с PDF, сжатие фото, расшифровка аудио и QR-коды.'
            );
        }

        if (window.RouterModule) window.RouterModule.refreshSeoHeader();
        if (window.DeAiModule) window.DeAiModule.runDeAi();
        if (window.StateModule && StateModule.refreshCounterLabel) StateModule.refreshCounterLabel();
    }

    return {
        setLang,
        getLang: () => currentLang,
        getRouteMeta: (path) => SEO_ROUTES[path] || SEO_ROUTES['/']
    };
